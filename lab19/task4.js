import { EventEmitter } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';
import { PluginManager } from './plugins.js';
const manager = new PluginManager();
manager.on('plugin:registered', name => console.log(`[477] Plagin zaregistrirovan: ${name}`));
manager.on('plugin:removed', name => console.log(`[477] Plagin udalen: ${name}`));
manager.register('LoggerPlugin', 'log', message => console.log(`[477] LOG: ${message}`));
manager.register('AlertPlugin', 'alert', message => console.log(`[477] ALERT: ${message}`));
manager.emit('log', 'Proverka plagina'); manager.emit('alert', 'Test'); manager.remove('LoggerPlugin');
const leak = new EventEmitter();
process.on('warning', warning => console.log(`[477] Preduprezhdenie Node: ${warning.name}`));
const listeners = Array.from({ length: 1010 }, () => () => {});
listeners.slice(0, 10).forEach(listener => leak.on('data', listener));
console.log(`Do dobavleniya: ${leak.listenerCount('data')}`);
listeners.slice(10).forEach(listener => leak.on('data', listener));
console.log(`Posle dobavleniya 1000: ${leak.listenerCount('data')}`);
listeners.forEach(listener => leak.removeListener('data', listener));
console.log(`Posle removeListener: ${leak.listenerCount('data')}`);
leak.removeAllListeners();
manager.on('async', async () => { await delay(100); console.log('[477] Async slushatel zavershen cherez 100ms'); });
manager.emit('async');
console.log('[477] emit vernulsya, ne ozhidaya async');
setImmediate(() => console.log('[477] setImmediate: otlozhennoe vypolnenie'));
await delay(150);
